"""Generate the zero-model report job from the ordinary bot's editorial inputs."""
from pathlib import Path
import argparse
import json
import yaml

ROOT = Path(__file__).resolve().parents[1]
PROFILE_KEYS = {
    "THEHEAT_WRITER_MODEL", "THEHEAT_WRITER_PROVIDER", "THEHEAT_FACT_CHECK_MODEL", "THEHEAT_CRITIC_MODEL",
    "GEMINI_SAFETY_MODEL", "THEHEAT_CHEAP_MODEL", "THEHEAT_CRITIC_ENABLED", "THEHEAT_WRITER_SAMPLES", "THEHEAT_CRITIC_REVISE_ENABLED",
    "THEHEAT_AUTOMATIC_PUBLICATION_ENABLED", "THEHEAT_STATE_BACKEND",
    "GEMINI_API_KEY", "ANTHROPIC_API_KEY", "GITHUB_TOKEN", "GIST_ID",
    "THEHEAT_PM25_FORECAST_AUTO_TEXT", "THEHEAT_DUST_FORECAST_AUTO_TEXT",
    "THEHEAT_NHC_ADVISORY_AUTO_TEXT", "THEHEAT_OFFICIAL_WARNING_AUTO_TEXT", "THEHEAT_NWS_WARNING_AUTO_TEXT",
    "THEHEAT_REGIONAL_OBSERVED", "THEHEAT_RAINFALL_WINDOW_PROVENANCE", "THEHEAT_HAZARD_EPISODES",
    "THEHEAT_PORTFOLIO_SELECTION", "THEHEAT_RAINFALL_REGIONAL_SCAN",
}


def render() -> str:
    bot = yaml.load((ROOT / ".github/workflows/bot.yml").read_text(), Loader=yaml.BaseLoader)
    job = bot["jobs"]["run"]
    step = next(step for step in job["steps"] if step.get("name") == "Run bot")
    env = {**bot.get("env", {}), **job.get("env", {}), **step["env"]}
    values = {key: value for key, value in env.items() if key in PROFILE_KEYS}
    for name in ("GEMINI_API_KEY", "ANTHROPIC_API_KEY", "GITHUB_TOKEN", "GIST_ID", "THEHEAT_CRITIC_ENABLED",
                 "THEHEAT_WRITER_SAMPLES", "THEHEAT_CRITIC_REVISE_ENABLED", "THEHEAT_AUTOMATIC_PUBLICATION_ENABLED"):
        if name not in values:
            raise ValueError("Ordinary bot profile is missing " + name)
    values.update(EXPECTED_COMMIT_SHA="${{ inputs.expected_commit_sha }}",
                  THEHEAT_PRODUCTION_PAUSED="${{ vars.THEHEAT_PRODUCTION_PAUSED }}")
    return '''# Generated by scripts/gen_runtime_report_workflow.py; do not hand-edit profile inputs.
name: runtime-configuration-report
on:
  workflow_dispatch:
    inputs:
      expected_commit_sha:
        description: Exact deployed commit; configuration only, no model or posting call
        required: true
        type: string
permissions:
  contents: read
concurrency:
  group: theheat-runtime-report
  cancel-in-progress: false
jobs:
  report:
    if: >-
      github.event_name == 'workflow_dispatch' &&
      github.ref == 'refs/heads/main' &&
      vars.THEHEAT_PRODUCTION_PAUSED == '1' &&
      vars.THEHEAT_AUTOMATIC_PUBLICATION_ENABLED != '1'
    runs-on: ubuntu-latest
    timeout-minutes: 5
    steps:
      - uses: actions/checkout@v6
      - uses: actions/setup-python@v6
        with:
          python-version: '3.12'
          cache: pip
      - name: Install existing application dependencies
        run: pip install -r requirements.txt
      - name: Verify ordinary editorial profile parity
        run: python scripts/gen_runtime_report_workflow.py --check
      - name: Publish configuration evidence only
        env:
''' + ''.join(f"          {key}: {json.dumps(value)}\n" for key, value in values.items()) + '''        run: python scripts/runtime_report.py
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / ".github/workflows/runtime-report.yml"
    value = render()
    if args.check:
        if not target.exists() or target.read_text() != value:
            print("Runtime report profile is stale; regenerate from the ordinary bot workflow.")
            return 1
    else:
        target.write_text(value)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
